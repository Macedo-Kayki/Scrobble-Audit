/**
 * Utilitários mínimos de DOM. `html` é um template tag que ESCAPA tudo que é
 * interpolado (nomes de músicas vêm de terceiros), exceto valores marcados
 * com `raw()` ou outros resultados de `html`.
 */
class SafeHtml {
  constructor(value) {
    this.value = value;
  }
  toString() {
    return this.value;
  }
}

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export function escapeHtml(v) {
  return String(v ?? '').replace(/[&<>"']/g, (c) => ESC[c]);
}

export function raw(value) {
  return new SafeHtml(String(value ?? ''));
}

function render(v) {
  if (v instanceof SafeHtml) return v.value;
  if (Array.isArray(v)) return v.map(render).join('');
  if (v === false || v === null || v === undefined) return '';
  return escapeHtml(v);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return new SafeHtml(out);
}

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

export function setHtml(el, content) {
  el.innerHTML = render(content);
}

/** Delegação de eventos: on(root, 'click', '[data-action]', (ev, el) => ...) */
export function on(root, type, selector, handler, opts) {
  const listener = (ev) => {
    const el = ev.target.closest(selector);
    if (el && root.contains(el)) handler(ev, el);
  };
  root.addEventListener(type, listener, opts);
  return () => root.removeEventListener(type, listener, opts);
}

export function debounce(fn, ms = 150) {
  let t;
  return (...args) => {
    clearTimeout(t);
    t = setTimeout(() => fn(...args), ms);
  };
}

